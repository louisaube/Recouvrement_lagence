// Regenerates src/schema.d.ts from the OpenAPI document of the running API.
//   pnpm api-client:generate   (API_URL, default http://localhost:4000)
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const apiUrl = process.env.API_URL ?? 'http://localhost:4000'
const output = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'schema.d.ts')

const response = await fetch(`${apiUrl}/api-json`)
if (!response.ok) throw new Error(`GET ${apiUrl}/api-json answered ${response.status}`)
const document = await response.json()

const ast = await openapiTS(document)
writeFileSync(output, `// Generated by scripts/generate.mjs from ${apiUrl}/api-json. Do not edit.\n${astToString(ast)}`)
console.log(`api-client: ${output} generated`)
